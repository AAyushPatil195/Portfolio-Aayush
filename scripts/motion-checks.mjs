import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';

const base = process.env.PREVIEW_URL || 'http://127.0.0.1:3000';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'no-preference' });
await page.goto(base, { waitUntil: 'networkidle' });
await page.waitForTimeout(1000);
const initial = await page.locator('.system-map').evaluate(el => getComputedStyle(el).transform);
await page.mouse.move(1130, 400);
await page.waitForTimeout(450);
assert.notEqual(await page.locator('.system-map').evaluate(el => getComputedStyle(el).transform), initial);
const cta = page.locator('.work-link');
const color = await cta.evaluate(el => getComputedStyle(el).backgroundColor);
await page.locator('.work-link').hover();
await page.waitForTimeout(300);
assert.notEqual(await cta.evaluate(el => getComputedStyle(el).backgroundColor), color);
const plate = page.locator('.playground-project');
const before = await plate.evaluate(el => getComputedStyle(el).transform);
await plate.scrollIntoViewIfNeeded();
await page.waitForTimeout(500);
assert.notEqual(await plate.evaluate(el => getComputedStyle(el).transform), before);
await page.emulateMedia({ reducedMotion: 'reduce' });
await page.waitForTimeout(100);
assert.equal(await plate.evaluate(el => getComputedStyle(el).transform), 'none');
await browser.close();
const report = { pointerDepth: true, ctaHover: true, scrollLinkedPlate: true, reducedMotionFallback: true };
await writeFile(`${process.env.CAPTURE_DIR || 'screenshots/playground-refinement'}/motion-verification.json`, JSON.stringify(report, null, 2));
console.log(report);
